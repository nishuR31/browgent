import { contextBridge, ipcRenderer } from 'electron';

type Privacy = 'balanced' | 'strict' | 'maximum';

contextBridge.exposeInMainWorld('browserAPI', {
  createSession: () => ipcRenderer.invoke('session:create'),
  closeSession: (id: string) => ipcRenderer.invoke('session:close', id),
  selectSession: (id: string) => ipcRenderer.invoke('session:select', id),
  navigate: (id: string, url: string) => ipcRenderer.invoke('session:navigate', id, url),
  back: (id: string) => ipcRenderer.invoke('session:back', id),
  forward: (id: string) => ipcRenderer.invoke('session:forward', id),
  reload: (id: string) => ipcRenderer.invoke('session:reload', id),
  saveDownload: (id: string, path: string) => ipcRenderer.invoke('download:save', id, path),
  getPrivacy: () => ipcRenderer.invoke('privacy:get'),
  setPrivacy: (level: Privacy) => ipcRenderer.invoke('privacy:set', level),
  installExtension: (id: string) => ipcRenderer.invoke('extensions:install', id),
  listExtensions: (id: string) => ipcRenderer.invoke('extensions:list', id),
  duplicateSession: (id: string) => ipcRenderer.invoke('session:duplicate', id),
  clearSessionData: (id: string) => ipcRenderer.invoke('session:clear-data', id),
  onState: (cb: (state: any) => void) => { const f = (_e: Electron.IpcRendererEvent, state: any) => cb(state); ipcRenderer.on('session:state', f); return () => ipcRenderer.removeListener('session:state', f); },
  onClosed: (cb: (id: string) => void) => { const f = (_e: Electron.IpcRendererEvent, id: string) => cb(id); ipcRenderer.on('session:closed', f); return () => ipcRenderer.removeListener('session:closed', f); },
  onDownload: (cb: (d: any) => void) => { const f = (_e: Electron.IpcRendererEvent, d: any) => cb(d); ipcRenderer.on('download:changed', f); return () => ipcRenderer.removeListener('download:changed', f); },
  debuggerAttached: (id: string) => ipcRenderer.invoke('session:debugger-attached', id),
  cdpSend: (id: string, method: string, params: any) => ipcRenderer.invoke('session:cdp-send', id, method, params),
  cdpDetach: (id: string) => ipcRenderer.invoke('session:cdp-detach', id),
  openDevtools: (id: string) => ipcRenderer.invoke('session:open-devtools', id),
  cdpPort: (id: string) => ipcRenderer.invoke('session:cdp-port', id),
  listPorts: () => ipcRenderer.invoke('session:list-ports'),
  screenshot: (id: string) => ipcRenderer.invoke('session:screenshot', id),
  querySelector: (id: string, selector: string) => ipcRenderer.invoke('session:query-selector', id, selector),
  clickElement: (id: string, selector: string) => ipcRenderer.invoke('session:click-element', id, selector),
  fillElement: (id: string, selector: string, value: string) => ipcRenderer.invoke('session:fill-element', id, selector, value),
  pressKey: (id: string, selector: string, key: string) => ipcRenderer.invoke('session:press-key', id, selector, key),
  waitForSelector: (id: string, selector: string, timeoutMs?: number) => ipcRenderer.invoke('session:wait-for-selector', id, selector, timeoutMs),
  waitForNavigation: (id: string, timeoutMs?: number) => ipcRenderer.invoke('session:wait-for-navigation', id, timeoutMs),
  consoleEvents: (id: string) => ipcRenderer.invoke('session:console-events', id),
  consoleErrors: (id: string) => ipcRenderer.invoke('session:console-errors', id),
  clearConsole: (id: string) => ipcRenderer.invoke('session:clear-console', id),
  enableNetworkInterception: (id: string, enabled?: boolean) => ipcRenderer.invoke('session:enable-network-interception', id, enabled),
  setBlockedUrls: (id: string, patterns: string[]) => ipcRenderer.invoke('session:set-blocked-urls', id, patterns),
  networkEvents: (id: string) => ipcRenderer.invoke('session:network-events', id),
  onConsoleEvent: (cb: (ev: any) => void) => { const f = (_e: Electron.IpcRendererEvent, ev: any) => cb(ev); ipcRenderer.on('session:event', f); return () => ipcRenderer.removeListener('session:event', f); },
  onConsoleError: (cb: (ev: any) => void) => { const f = (_e: Electron.IpcRendererEvent, ev: any) => { if (ev.kind === 'errors') cb(ev.event); }; ipcRenderer.on('session:event', f); return () => ipcRenderer.removeListener('session:event', f); },
  onNetworkEvent: (cb: (ev: any) => void) => { const f = (_e: Electron.IpcRendererEvent, ev: any) => { if (ev.kind === 'network') cb(ev.event); }; ipcRenderer.on('session:event', f); return () => ipcRenderer.removeListener('session:event', f); },
  auditAccessibility: (id: string) => ipcRenderer.invoke('session:audit-accessibility', id),
  islandCreate: () => ipcRenderer.invoke('island:create'),
  islandClose: (id: string) => ipcRenderer.invoke('island:close', id),
  islandSelect: (id: string) => ipcRenderer.invoke('island:select', id),
  islandList: () => ipcRenderer.invoke('island:list'),
  islandDuplicate: (id: string) => ipcRenderer.invoke('island:duplicate', id),
  clearIslandData: (id: string) => ipcRenderer.invoke('island:clear-data', id),
  tabCreate: (islandId: string, url: string) => ipcRenderer.invoke('tab:create', islandId, url),
  tabClose: (islandId: string, tabId: string) => ipcRenderer.invoke('tab:close', islandId, tabId),
  tabSelect: (islandId: string, tabId: string) => ipcRenderer.invoke('tab:select', islandId, tabId),
  tabBack: (islandId: string, tabId: string) => ipcRenderer.invoke('tab:back', islandId, tabId),
  tabForward: (islandId: string, tabId: string) => ipcRenderer.invoke('tab:forward', islandId, tabId),
  tabReload: (islandId: string, tabId: string) => ipcRenderer.invoke('tab:reload', islandId, tabId),
  tabNavigate: (islandId: string, tabId: string, url: string) => ipcRenderer.invoke('tab:navigate', islandId, tabId, url),
  webview: {
    setBounds: (tabId: string, bounds: any) => ipcRenderer.invoke('webview:setBounds', tabId, bounds),
    setVisible: (tabId: string, visible: boolean) => ipcRenderer.invoke('webview:setVisible', tabId, visible),
  },
});

